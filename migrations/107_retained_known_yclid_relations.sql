-- Inert private derived evidence for the two already frozen known-CID cases; no delivery or schedule changes.
CREATE TABLE IF NOT EXISTS modeled_conversion_known_yclid_relations (
    purpose VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    outbox_id BIGINT UNSIGNED NOT NULL,
    case_index TINYINT UNSIGNED NOT NULL,
    namespace CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    frame_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_ref CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    intent_at_unix BIGINT UNSIGNED NOT NULL,
    intent_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    r1_request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    r2_request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    r1_requested_at_unix BIGINT UNSIGNED NULL,
    r2_requested_at_unix BIGINT UNSIGNED NULL,
    plan_json JSON NOT NULL,
    source_json JSON NULL,
    r1_json JSON NULL,
    r2_json JSON NULL,
    completed_at_unix BIGINT UNSIGNED NULL,
    PRIMARY KEY (purpose,outbox_id),
    UNIQUE KEY uq_known_relation_frame_case (purpose,frame_digest,case_index),
    CONSTRAINT ck_known_relation_purpose CHECK (purpose='retained_known_yclid_two_stage_v1'),
    CONSTRAINT ck_known_relation_case CHECK (case_index IN (1,2)),
    CONSTRAINT ck_known_relation_state CHECK (state IN ('intent','complete')),
    CONSTRAINT ck_known_relation_plan CHECK (OCTET_LENGTH(plan_json)<=4096),
    CONSTRAINT ck_known_relation_source CHECK (source_json IS NULL OR OCTET_LENGTH(source_json)<=4096),
    CONSTRAINT ck_known_relation_r1 CHECK (r1_json IS NULL OR OCTET_LENGTH(r1_json)<=16384),
    CONSTRAINT ck_known_relation_r2 CHECK (r2_json IS NULL OR OCTET_LENGTH(r2_json)<=65536)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
