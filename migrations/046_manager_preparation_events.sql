-- Private authenticated MCP subscription state. Payloads contain queue counts only.
CREATE TABLE IF NOT EXISTS manager_preparation_events (
    subscription_id CHAR(68) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    admin_id BIGINT UNSIGNED NOT NULL,
    oauth_connection_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    project_key VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    event_name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    arguments_json VARBINARY(1024) NOT NULL,
    callback_url VARBINARY(2048) NOT NULL,
    signing_secret VARBINARY(128) NOT NULL,
    previous_secret VARBINARY(128) NULL,
    previous_secret_until DATETIME NULL,
    verified_at DATETIME NOT NULL,
    expires_at DATETIME NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    observed_jobs_json BLOB NOT NULL,
    pending_event_id VARCHAR(68) CHARACTER SET ascii COLLATE ascii_bin NULL,
    pending_body VARBINARY(4096) NULL,
    pending_jobs_json BLOB NULL,
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    next_attempt_at DATETIME NULL,
    lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME NULL,
    last_batch_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    last_status SMALLINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (subscription_id),
    KEY idx_manager_preparation_events_active (project_key,is_active,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
